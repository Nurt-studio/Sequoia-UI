//! A small registry for organizing shader sources before they reach `App`.

use std::io;
use std::path::Path;

use crate::SequoiShader;

/// Named WGSL sources collected from typed shaders, raw modules, and files.
///
/// The registry is a plain value: build it once, pass it to the app, and reuse
/// it in tests. Inserting an existing name replaces the source in place, so
/// re-registering a shader (for example from two feature modules) does not
/// produce duplicate GPU pipelines.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ShaderRegistry {
    entries: Vec<(String, String)>,
}

impl ShaderRegistry {
    pub fn new() -> Self {
        Self::default()
    }

    /// Adds a compile-time shader generated by [`macro@crate::shader`].
    pub fn with<S: SequoiShader>(mut self) -> Self {
        self.insert_type::<S>();
        self
    }

    /// Adds a complete WGSL module under `name`.
    pub fn with_raw(mut self, name: impl Into<String>, wgsl: impl Into<String>) -> Self {
        self.insert(name, wgsl);
        self
    }

    /// Adds a WGSL file read from disk. Errors are returned, not logged, so
    /// startup code decides whether a missing optional shader is fatal.
    pub fn with_file(
        mut self,
        name: impl Into<String>,
        path: impl AsRef<Path>,
    ) -> io::Result<Self> {
        self.insert_file(name, path)?;
        Ok(self)
    }

    /// Adds every `.wgsl` file below `dir`, naming them by relative path.
    pub fn with_dir(mut self, dir: impl AsRef<Path>) -> io::Result<Self> {
        self.insert_dir(dir)?;
        Ok(self)
    }

    pub fn insert_type<S: SequoiShader>(&mut self) -> &mut Self {
        self.insert(S::NAME, S::WGSL);
        self
    }

    pub fn insert(&mut self, name: impl Into<String>, wgsl: impl Into<String>) -> &mut Self {
        let name = name.into();
        let wgsl = wgsl.into();
        if let Some(entry) = self.entries.iter_mut().find(|(n, _)| *n == name) {
            entry.1 = wgsl;
        } else {
            self.entries.push((name, wgsl));
        }
        self
    }

    pub fn insert_file(
        &mut self,
        name: impl Into<String>,
        path: impl AsRef<Path>,
    ) -> io::Result<&mut Self> {
        let wgsl = std::fs::read_to_string(path)?;
        self.insert(name, wgsl);
        Ok(self)
    }

    /// Recursively inserts `.wgsl` files. Names use `/` separators and drop
    /// the extension: `effects/invert.wgsl` becomes `effects/invert`.
    pub fn insert_dir(&mut self, dir: impl AsRef<Path>) -> io::Result<&mut Self> {
        let dir = dir.as_ref();
        let mut found = Vec::new();
        collect_wgsl(dir, dir, &mut found)?;
        for (name, wgsl) in found {
            self.insert(name, wgsl);
        }
        Ok(self)
    }

    pub fn get(&self, name: &str) -> Option<&str> {
        self.entries
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, wgsl)| wgsl.as_str())
    }

    pub fn contains(&self, name: &str) -> bool {
        self.entries.iter().any(|(n, _)| n == name)
    }

    pub fn names(&self) -> impl Iterator<Item = &str> + '_ {
        self.entries.iter().map(|(name, _)| name.as_str())
    }

    pub fn iter(&self) -> impl Iterator<Item = (&str, &str)> + '_ {
        self.entries
            .iter()
            .map(|(name, wgsl)| (name.as_str(), wgsl.as_str()))
    }

    pub fn entries(&self) -> &[(String, String)] {
        &self.entries
    }

    pub fn into_entries(self) -> Vec<(String, String)> {
        self.entries
    }

    pub fn extend(&mut self, entries: impl IntoIterator<Item = (String, String)>) -> &mut Self {
        for (name, wgsl) in entries {
            self.insert(name, wgsl);
        }
        self
    }

    pub fn merge(&mut self, other: ShaderRegistry) -> &mut Self {
        self.extend(other.into_entries());
        self
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }
}

fn collect_wgsl(dir: &Path, base: &Path, out: &mut Vec<(String, String)>) -> io::Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)?.collect::<Result<_, _>>()?;
    entries.sort_by_key(|entry| entry.path());
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect_wgsl(&path, base, out)?;
        } else if path.extension().and_then(|e| e.to_str()) == Some("wgsl") {
            let relative = path.strip_prefix(base).unwrap_or(&path);
            let name = relative
                .with_extension("")
                .to_string_lossy()
                .replace('\\', "/");
            out.push((name, std::fs::read_to_string(&path)?));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::shader;

    shader! {
        fn solid(color: Color) -> Color {
            return color;
        }
    }

    #[test]
    fn typed_and_raw_entries_dedupe_by_name() {
        let mut registry = ShaderRegistry::new();
        registry.insert_type::<Solid>();
        assert_eq!(registry.len(), 1);
        assert!(registry.contains(Solid::NAME));

        registry.insert(Solid::NAME, "replacement");
        assert_eq!(registry.len(), 1);
        assert_eq!(registry.get(Solid::NAME), Some("replacement"));
        assert_eq!(registry.names().collect::<Vec<_>>(), vec![Solid::NAME]);
    }

    #[test]
    fn merging_prefers_the_later_source() {
        let mut a = ShaderRegistry::new().with_raw("effect", "first");
        let b = ShaderRegistry::new()
            .with_raw("effect", "second")
            .with_raw("other", "x");
        a.merge(b);
        assert_eq!(a.len(), 2);
        assert_eq!(a.get("effect"), Some("second"));
        assert!(a.contains("other"));
    }

    #[test]
    fn directory_names_are_relative_and_sorted() {
        let root =
            std::env::temp_dir().join(format!("sequoia-shader-registry-{}", std::process::id()));
        let nested = root.join("effects");
        std::fs::create_dir_all(&nested).expect("temp dir");
        std::fs::write(root.join("z.wgsl"), "z").expect("write");
        std::fs::write(nested.join("invert.wgsl"), "invert").expect("write");
        std::fs::write(root.join("ignore.txt"), "no").expect("write");

        let registry = ShaderRegistry::new().with_dir(&root).expect("scan");
        let names: Vec<_> = registry.names().collect();
        assert_eq!(names, vec!["effects/invert", "z"]);
        assert_eq!(registry.get("effects/invert"), Some("invert"));

        std::fs::remove_dir_all(&root).ok();
    }
}
