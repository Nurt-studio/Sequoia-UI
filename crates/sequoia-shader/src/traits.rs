/// First bind group reserved for shader texture inputs.
pub const TEXTURE_GROUP_BASE: u32 = 1;

/// Maximum number of textures a generated shader can declare.
pub const MAX_TEXTURES: usize = 3;

/// Fragment local coordinates in pixels.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct FragPos;

/// Fragment texture coordinates in the range `0..=1`.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct FragUv;

/// Fragment world coordinates in pixels.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct FragWorld;

/// Fragment local coordinates in pixels (alias of [`FragPos`]).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct FragLocal;

/// Zero-based vertex index of the instanced quad.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct VertexIndex;

/// A custom fragment shader generated by [`macro@crate::shader`].
///
/// Implementations carry both the uniform payload and the complete WGSL module
/// validated at compile time by the attribute macro.
pub trait SequoiShader {
    /// Registration name used by [`crate::shader`] and the platform layer.
    const NAME: &'static str;

    /// Complete WGSL module including the engine vertex and fragment ABI.
    const WGSL: &'static str;

    /// Texture parameter names in binding order.
    const TEXTURES: &'static [&'static str];

    /// Size of the encoded uniform payload in bytes.
    const UNIFORM_SIZE: usize;

    /// Appends the uniform payload to `out`.
    fn encode_uniforms(&self, out: &mut Vec<u8>);
}
