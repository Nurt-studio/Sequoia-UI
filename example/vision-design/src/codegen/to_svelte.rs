//! AST → Svelte code. Deterministic and parseable back.

use std::collections::HashSet;

use sequoia_ui::prelude::Color;

use crate::model::svelte_ast::*;

pub fn to_svelte(root: &Option<SvelteNode>) -> String {
    let mut ctx = Ctx {
        names: HashSet::new(),
        styles: Vec::new(),
    };
    let body = match root {
        Some(r) => node_markup(r, &mut ctx, 0),
        None => "  <!-- empty -->\n".to_string(),
    };
    let mut out = String::new();
    out.push_str("<script lang=\"ts\">\n  // generated by Vision Design\n</script>\n\n");
    out.push_str(&body);
    out.push_str("\n<style>\n");
    for s in &ctx.styles {
        out.push_str(s);
    }
    out.push_str("</style>\n");
    out
}

struct Ctx {
    names: HashSet<String>,
    styles: Vec<String>,
}

fn unique_class(base: &str, ctx: &mut Ctx) -> String {
    let mut candidate: String = base
        .to_lowercase()
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '-' })
        .collect();
    candidate = candidate.trim_matches('-').to_string();
    if candidate.is_empty() {
        candidate = "node".into();
    }
    if candidate.chars().next().map_or(true, |c| c.is_ascii_digit()) {
        candidate = format!("n-{}", candidate);
    }
    let mut i = 1;
    let mut final_name = candidate.clone();
    while ctx.names.contains(&final_name) {
        i += 1;
        final_name = format!("{}-{}", candidate, i);
    }
    ctx.names.insert(final_name.clone());
    final_name
}

fn node_markup(node: &SvelteNode, ctx: &mut Ctx, depth: usize) -> String {
    let indent = "  ".repeat(depth);
    match node {
        SvelteNode::Element(e) => {
            let class = unique_class(&e.name, ctx);
            ctx.styles.push(render_style(&class, &e.style));
            let tag = e.tag.as_str();
            if e.children.is_empty() {
                format!("{indent}<{tag} class=\"{class}\"></{tag}>\n")
            } else {
                let mut out = format!("{indent}<{tag} class=\"{class}\">\n");
                for c in &e.children {
                    out.push_str(&node_markup(c, ctx, depth + 1));
                }
                out.push_str(&format!("{indent}</{tag}>\n"));
                out
            }
        }
        SvelteNode::Text(t) => {
            let class = unique_class(&t.name, ctx);
            ctx.styles.push(render_text_style(&class, &t.style, t.width, t.height));
            format!(
                "{indent}<span class=\"{class}\">{}</span>\n",
                escape_text(&t.content)
            )
        }
    }
}

fn escape_text(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

fn fmt_opt(v: Option<f32>) -> String {
    match v {
        Some(v) if v.fract() == 0.0 => format!("{}px", v as i32),
        Some(v) => format!("{:.2}px", v),
        None => "auto".into(),
    }
}

fn fmt_dim(v: Dimension) -> String {
    match v {
        Dimension::Auto => "auto".into(),
        Dimension::Fill => "100%".into(),
        Dimension::Fixed(v) if v.fract() == 0.0 => format!("{}px", v as i32),
        Dimension::Fixed(v) => format!("{:.2}px", v),
    }
}

fn fmt_color(c: Color) -> String {
    let rgba = c.to_rgba8();
    if rgba.3 == 255 {
        format!("#{:02X}{:02X}{:02X}", rgba.0, rgba.1, rgba.2)
    } else {
        format!("rgba({},{},{},{:.3})", rgba.0, rgba.1, rgba.2, rgba.3 as f32 / 255.0)
    }
}

fn render_style(class: &str, s: &Style) -> String {
    let mut rules: Vec<String> = Vec::new();

    match s.display {
        Display::Flex => {
            rules.push("display: flex".into());
            rules.push(format!(
                "flex-direction: {}",
                if s.flex_dir == FlexDir::Row { "row" } else { "column" }
            ));
            if s.gap > 0.0 {
                rules.push(format!("gap: {}px", s.gap));
            }
            if s.align_items != Align::Start {
                rules.push(format!("align-items: {}", s.align_items.css_items()));
            }
            if s.justify_content != Align::Start {
                rules.push(format!("justify-content: {}", s.justify_content.css_content()));
            }
        }
        Display::Grid => {
            rules.push("display: grid".into());
            if let Some(n) = s.grid_cols {
                rules.push(format!("grid-template-columns: repeat({n}, 1fr)"));
            }
            if s.gap > 0.0 {
                rules.push(format!("gap: {}px", s.gap));
            }
        }
        Display::None => {}
    }

    if s.position == Position::Absolute {
        rules.push("position: absolute".into());
    }
    if let Some(t) = s.top {
        rules.push(format!("top: {}px", t));
    }
    if let Some(r) = s.right {
        rules.push(format!("right: {}px", r));
    }
    if let Some(b) = s.bottom {
        rules.push(format!("bottom: {}px", b));
    }
    if let Some(l) = s.left {
        rules.push(format!("left: {}px", l));
    }

    if let Dimension::Fixed(v) = s.width {
        rules.push(format!("width: {}px", v));
    } else if s.width.is_fill() {
        rules.push("width: 100%".into());
    }
    if let Dimension::Fixed(v) = s.height {
        rules.push(format!("height: {}px", v));
    } else if s.height.is_fill() {
        rules.push("height: 100%".into());
    }

    if s.padding.top != 0.0 || s.padding.right != 0.0
        || s.padding.bottom != 0.0 || s.padding.left != 0.0
    {
        rules.push(format!(
            "padding: {}px {}px {}px {}px",
            s.padding.top, s.padding.right, s.padding.bottom, s.padding.left
        ));
    }

    if let Some(f) = s.fill {
        rules.push(format!("background: {}", fmt_color(f)));
    }
    if let (Some(sc), w) = (s.stroke, s.stroke_width) {
        if w > 0.0 {
            rules.push(format!("border: {}px solid {}", w, fmt_color(sc)));
        }
    }
    if s.radius > 0.0 {
        if s.radius >= 999.0 {
            rules.push("border-radius: 50%".into());
        } else {
            rules.push(format!("border-radius: {}px", s.radius));
        }
    }
    if s.opacity < 100.0 {
        rules.push(format!("opacity: {}", s.opacity / 100.0));
    }

    let body = rules
        .iter()
        .map(|r| format!("  {r};\n"))
        .collect::<String>();
    format!(".{class} {{\n{body}}}\n\n")
}

fn render_text_style(
    class: &str,
    t: &TextStyle,
    w: Option<f32>,
    h: Option<f32>,
) -> String {
    let mut rules: Vec<String> = Vec::new();
    if let Some(v) = w {
        rules.push(format!("width: {}px", v));
    }
    if let Some(v) = h {
        rules.push(format!("height: {}px", v));
    }
    rules.push(format!("font-size: {}px", t.font_size));
    if t.font_weight != 400 {
        rules.push(format!("font-weight: {}", t.font_weight));
    }
    rules.push(format!("color: {}", fmt_color(t.color)));
    if t.align != Align::Start {
        rules.push(format!(
            "text-align: {}",
            match t.align {
                Align::Center => "center",
                Align::End => "right",
                _ => "left",
            }
        ));
    }
    let body = rules
        .iter()
        .map(|r| format!("  {r};\n"))
        .collect::<String>();
    format!(".{class} {{\n{body}}}\n\n")
}

#[allow(dead_code)]
fn _unused(_: Option<f32>) -> String { fmt_opt(None) }
#[cfg(test)]
mod tests {
    use super::*;
    use crate::codegen::from_svelte;

    #[test]
    fn generated_code_roundtrips() {
        let root = Some(crate::document::demo::demo_tree());
        let code1 = to_svelte(&root);
        let parsed = from_svelte(&code1).expect("parser akceptuje własny kod");
        let code2 = to_svelte(&parsed);
        assert_eq!(code1, code2, "runda AST→kod→AST→kod musi być stabilna");
    }

    #[test]
    fn empty_document_renders_placeholder() {
        let code = to_svelte(&None);
        assert!(code.contains("<!-- empty -->"));
        assert!(code.contains("<style>"));
    }

    #[test]
    fn class_names_are_unique_and_valid() {
        let code = to_svelte(&Some(crate::document::demo::demo_tree()));
        // every CSS class used in the markup has a section in <style>
        let mut opens = 0;
        for line in code.lines() {
            if line.starts_with('<') && !line.contains("</") {
                opens += 1;
            }
        }
        let rules = code.matches(".{").count() + code.matches('{').count();
        assert!(opens > 0);
        assert!(rules >= opens, "sekcje CSS: {rules}, tagi: {opens}");
    }
}
